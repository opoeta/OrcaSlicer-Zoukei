"  float specular = a2 / (PI * d * d) * g * f / (4.0 * n_dot_v * n_dot_l + 1e-4);\n"
"  return ((1.0 - f) * base / PI + vec3(specular)) * intensity * n_dot_l;\n"
"}\n"
"vec3 lit_color(vec3 base_srgb, vec3 position, vec3 n, float key_shadow) {\n"
"  vec3 v = projection_matrix[3][3] == 1.0 ? vec3(0.0, 0.0, 1.0) : normalize(-(view_matrix * vec4(position, 1.0)).xyz);\n"
"  vec3 base = pow(clamp(base_srgb, 0.0, 1.0), vec3(2.2));\n"
"  vec3 c = AMBIENT * base + key_shadow * light_radiance(base, n, v, light_key_dir, KEY_RADIANCE) +\n"
"           light_radiance(base, n, v, FILL_DIR, FILL_RADIANCE);\n"
"  return c * (1.0 + c / WHITE_SQ) / (1.0 + c);\n"
"}\n"
"void main() {\n"
"  if (clipping_plane_dot < 0.0)\n"
"    discard;\n"
"  if (prusa3 == 0) {\n"
"    fragment_color = vec4(color, 1.0);\n"
"    return;\n"
"  }\n"
"  vec3 n = normalize(eye_normal_v);\n"
"  float key_shadow = shadow_shade(world_position, n);\n"
"  vec3 c = realistic == 0 ? lit_color_classic(base_color, world_position, n, key_shadow) :\n"
"                            lit_color(base_color, world_position, n, key_shadow);\n"
"  c *= exposure;\n"
"  c = mix(vec3(dot(c, LUMA)), c, saturation);\n"
"  fragment_color = vec4(clamp(c, 0.0, 1.0), 1.0);\n"
"}\n";

