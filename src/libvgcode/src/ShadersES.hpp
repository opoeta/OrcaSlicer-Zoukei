static const char* Segments_Fragment_Shader_ES =
"#version 300 es\n"
"precision highp float;\n"
// ORCA: section view - segment ids exceed mediump
"precision highp int;\n"
"// ORCA: sampler2D defaults to lowp in an ES fragment shader, far too coarse to compare\n"
"// shadow map depths against.\n"
"precision highp sampler2D;\n"
"// ORCA: realistic view - object-on-object and self shadows, read from the same depth map the\n"
"// rest of the 3D scene samples. shadow_intensity == 0, the default, short-circuits the lookup,\n"
"// so the toolpaths shade exactly as before whenever realistic view is off.\n"
"uniform vec3 light_top_dir;\n"
"uniform sampler2D shadow_map;\n"
"uniform mat4 shadow_light_vp;\n"
"uniform float shadow_intensity;\n"
"uniform float shadow_map_texel;\n"
// ORCA: the lighting term peaks near 0.9 and every later multiplier - the shadow, then the SSAO
// post pass - only takes more light away, so the print reads dimmer and duller than the legend
// colours. These pay that back. Both are 1.0 for an untouched image; what the caller actually
// passes in each mode is decided in GLCanvas3D::_render_gcode, not here.
"uniform float exposure;\n"
"uniform float saturation;\n"
// ORCA: section view - cut faces are ray cast; data samplers stay lowp as in the vertex shader
"uniform vec4 clipping_plane;\n"
"uniform mat4 view_matrix;\n"
"uniform mat4 projection_matrix;\n"
"uniform vec3 camera_position;\n"
"uniform lowp sampler2D position_tex;\n"
"uniform lowp sampler2D height_width_angle_tex;\n"
"const vec3 UP = vec3(0, 0, 1);\n"
"const vec3 LUMA = vec3(0.2126, 0.7152, 0.0722);\n"
"in vec3 color;\n"
"in vec3 world_position;\n"
"in vec3 shadow_normal;\n"
"flat in int segment_id;\n"
"in vec3 bead;\n"
"in vec2 bead_half;\n"
"flat in vec3 bead_right;\n"
"flat in vec3 bead_up;\n"
"flat in vec3 bead_along;\n"
"out vec4 fragment_color;\n"
"float shadow_shade(vec3 position, vec3 normal) {\n"
"  if (shadow_intensity <= 0.0)\n"
"    return 1.0;\n"
"  vec4 lp = shadow_light_vp * vec4(position, 1.0);\n"
"  vec3 proj = lp.xyz / lp.w;\n"
"  proj = proj * 0.5 + 0.5;\n"
"  if (proj.z > 1.0)\n"
"    return 1.0;\n"
"  // Slope-scaled bias, as in gouraud.fs. An extrusion is only a handful of shadow-map texels\n"
"  // wide, so grazing faces need the larger bias to keep self-shadow acne off the top surfaces.\n"
"  float NdotL = dot(normalize(normal), light_top_dir);\n"
"  float bias = mix(0.0004, 0.004, clamp(1.0 - NdotL, 0.0, 1.0));\n"
"  float sum = 0.0;\n"
"  for (int x = -2; x <= 2; ++x) {\n"
"    for (int y = -2; y <= 2; ++y) {\n"
"      float closest = texture(shadow_map, proj.xy + vec2(float(x), float(y)) * shadow_map_texel).r;\n"
"      sum += (proj.z - bias > closest) ? 1.0 : 0.0;\n"
"    }\n"
"  }\n"
"  return 1.0 - shadow_intensity * (sum / 25.0);\n"
"}\n"
"vec4 fetch(lowp sampler2D sampler, int id) {\n"
"  ivec2 tex_size = textureSize(sampler, 0);\n"
"  return texelFetch(sampler, (tex_size.y == 1) ? ivec2(id, 0) : ivec2(id % tex_size.x, id / tex_size.x), 0);\n"
"}\n"
// ORCA: section view - where the view ray meets the plane, if inside the extrusion's diamond section
"bool find_cut(out vec3 cut) {\n"
// parallel rays for an orthographic projection
"  vec3 ray = projection_matrix[3][3] == 1.0 ? -vec3(view_matrix[0][2], view_matrix[1][2], view_matrix[2][2]) :\n"
"                                             normalize(world_position - camera_position);\n"
"  float approach = dot(clipping_plane.xyz, ray);\n"
"  if (approach <= 0.0)\n"
"    return false;\n"
"  cut = world_position - dot(vec4(world_position, 1.0), clipping_plane) / approach * ray;\n"
"  vec3 pos_a = fetch(position_tex, segment_id).xyz;\n"
"  vec3 line = fetch(position_tex, segment_id + 1).xyz - pos_a;\n"
"  float length_sq = dot(line, line);\n"
"  float along = length_sq < 1e-8 ? -1.0 : dot(cut - pos_a, line) / length_sq;\n"
"  if (along < 0.0 || along > 1.0)\n"
"    return false;\n"
"  vec3 line_dir = line * inversesqrt(length_sq);\n"
"  vec3 right_dir = abs(dot(line_dir, UP)) > 0.9 ? normalize(cross(vec3(1, 0, 0), line_dir)) : normalize(cross(line_dir, UP));\n"
"  vec3 offset = cut - pos_a - along * line;\n"
"  vec2 half_height_width = 0.5 * mix(fetch(height_width_angle_tex, segment_id).xy,\n"
"                                     fetch(height_width_angle_tex, segment_id + 1).xy, along);\n"
"  return abs(dot(offset, right_dir)) / half_height_width.y + abs(dot(offset, cross(right_dir, line_dir))) / half_height_width.x <= 1.0;\n"
"}\n"
// ORCA: realistic preview, ported from PrusaSlicer 3.0 (AGPL-3.0, Prusa Research): its two lights
// (key 0.48 and fill 0.18 diffuse, scaled by its PBR intensity 20, ambient 0.5) and its G-code
// material (dielectric, roughness 0.5, IOR 1.5) lit with the Cook-Torrance GGX BRDF in linear light.
// PrusaSlicer tone maps with Reinhard and skips the gamma encoding; the white point used here keeps
// the brightest legend colours from greying out. Its screen space ambient occlusion is approximated
// per fragment from the bead normal: flanks turned down sit against the layer below.
"const vec3 FILL_DIR = vec3(0.6985074, 0.1397015, 0.6985074);\n"
// ORCA: classic shading (realistic preview off): key and fill lights plus a hemispheric ambient, a faint
// plastic specular and a darkening of the grazing edges, lit in linear light, output gamma-encoded.
"uniform int realistic;\n"
"vec3 lit_color_classic(vec3 base_srgb, vec3 position, vec3 normal, float key_shadow) {\n"
"  vec3 n = normalize(normal);\n"
"  vec3 v = normalize(-(view_matrix * vec4(position, 1.0)).xyz);\n"
"  vec3 base = pow(clamp(base_srgb, 0.0, 1.0), vec3(2.2));\n"
"  float sky = 0.5 + 0.5 * dot(n, mat3(view_matrix) * UP);\n"
"  float hemi = mix(0.28, 0.5, sky);\n"
"  float key = max(dot(n, light_top_dir), 0.0);\n"
"  float fill = max(dot(n, FILL_DIR), 0.0);\n"
"  float spec = key > 0.0 ? pow(max(dot(n, normalize(light_top_dir + v)), 0.0), 40.0) * 0.12 : 0.0;\n"
"  float edge = mix(0.7, 1.0, smoothstep(0.0, 0.5, clamp(dot(n, v), 0.0, 1.0)));\n"
"  vec3 lit = base * (hemi + 0.55 * key * key_shadow + 0.2 * fill) * edge + vec3(spec * key_shadow);\n"
"  return pow(clamp(lit, 0.0, 1.0), vec3(1.0 / 2.2));\n"
"}\n"
"const float PI = 3.14159265;\n"
"const float KEY_RADIANCE = 9.6;\n"
"const float FILL_RADIANCE = 3.6;\n"
"const float AMBIENT = 0.5;\n"
"const float ROUGHNESS = 0.5;\n"
"const float F0 = 0.04;\n"
"const float WHITE_SQ = 16.0;\n"
// The bead seen in section: a rectangle as wide and as tall as the extrusion with its corners
// rounded to half the smaller side (flat top, half round flanks); the ends and the outside of a
// bend are revolved the same way. The diamond the vertex shader draws is projected radially onto it,
// which keeps both a top surface seen from above and a wall seen from the side in proportion.
"vec3 bead_normal() {\n"
"  float r = max(min(bead_half.x, bead_half.y), 1e-4);\n"
"  vec2 core = max(bead_half - vec2(r), vec2(0.0));\n"
"  float rho = length(bead.xz);\n"
"  vec3 h = rho > 1e-6 ? (bead.x * bead_right + bead.z * bead_along) / rho : bead_right;\n"
"  vec2 d = vec2(rho, abs(bead.y));\n"
"  float len = length(d);\n"
"  d = len > 1e-6 ? d / len : vec2(0.0, 1.0);\n"
"  vec2 n;\n"
"  if (d.x * bead_half.y <= core.x * d.y)\n"
"    n = vec2(0.0, 1.0);\n"
"  else if (d.y * bead_half.x <= core.y * d.x)\n"
"    n = vec2(1.0, 0.0);\n"
"  else {\n"
"    float dc = dot(d, core);\n"
"    float s = dc + sqrt(max(dc * dc - dot(core, core) + r * r, 0.0));\n"
"    n = normalize(s * d - core);\n"
"  }\n"
"  return normalize(h * n.x + bead_up * ((bead.y < 0.0 ? -1.0 : 1.0) * n.y));\n"
"}\n"
"float distribution_ggx(float n_dot_h) {\n"
"  float a2 = ROUGHNESS * ROUGHNESS * ROUGHNESS * ROUGHNESS;\n"
"  float d = n_dot_h * n_dot_h * (a2 - 1.0) + 1.0;\n"
"  return a2 / (PI * d * d);\n"
"}\n"
"float geometry_schlick_ggx(float c) {\n"
"  float k = (ROUGHNESS + 1.0) * (ROUGHNESS + 1.0) / 8.0;\n"
"  return c / (c * (1.0 - k) + k);\n"
"}\n"
"vec3 light_radiance(vec3 base, vec3 n, vec3 v, vec3 l, float intensity) {\n"
"  float n_dot_l = max(dot(n, l), 0.0);\n"
"  if (n_dot_l <= 0.0)\n"
"    return vec3(0.0);\n"
"  vec3 h = normalize(v + l);\n"
"  float n_dot_v = max(dot(n, v), 0.0);\n"
"  float f = F0 + (1.0 - F0) * pow(clamp(1.0 - dot(h, v), 0.0, 1.0), 5.0);\n"
"  float specular = distribution_ggx(max(dot(n, h), 0.0)) * geometry_schlick_ggx(n_dot_v) * geometry_schlick_ggx(n_dot_l) * f /\n"
"                   (4.0 * n_dot_v * n_dot_l + 1e-4);\n"
"  return ((1.0 - f) * base / PI + vec3(specular)) * intensity * n_dot_l;\n"
"}\n"
"vec3 lit_color(vec3 base_srgb, vec3 position, vec3 normal, float key_shadow, float ao) {\n"
"  vec3 n = normalize(normal);\n"
"  vec3 v = projection_matrix[3][3] == 1.0 ? vec3(0.0, 0.0, 1.0) : normalize(-(view_matrix * vec4(position, 1.0)).xyz);\n"
"  vec3 base = pow(clamp(base_srgb, 0.0, 1.0), vec3(2.2));\n"
"  float direct_ao = mix(1.0, ao, 0.5);\n"
"  vec3 c = AMBIENT * ao * base +\n"
"           direct_ao * (key_shadow * light_radiance(base, n, v, light_top_dir, KEY_RADIANCE) +\n"
"                        light_radiance(base, n, v, FILL_DIR, FILL_RADIANCE));\n"
"  return c * (1.0 + c / WHITE_SQ) / (1.0 + c);\n"
"}\n"
"void main() {\n"
"  vec3 c;\n"
"  if (dot(vec4(world_position, 1.0), clipping_plane) >= 0.0) {\n"
"    if (realistic == 0)\n"
"      c = lit_color_classic(color, world_position, shadow_normal, shadow_shade(world_position, shadow_normal));\n"
"    else {\n"
"    vec3 world_normal = bead_normal();\n"
"    vec3 normal = mat3(view_matrix) * world_normal;\n"
"    float ao = 1.0 - 0.3 * smoothstep(0.0, 1.0, -world_normal.z);\n"
"    c = lit_color(color, world_position, normal, shadow_shade(world_position, normal), ao);\n"
"    }\n"
"  }\n"
"  else {\n"
"    vec3 cut;\n"
"    if (!find_cut(cut))\n"
"      discard;\n"
"    vec3 cut_normal = mat3(view_matrix) * -clipping_plane.xyz;\n"
"    if (realistic == 0)\n"
"      c = lit_color_classic(color, cut, cut_normal, shadow_shade(cut, cut_normal));\n"
"    else\n"
"      c = lit_color(color, cut, cut_normal, shadow_shade(cut, cut_normal), 1.0);\n"
"  }\n"
"  c *= exposure;\n"
"  c = mix(vec3(dot(c, LUMA)), c, saturation);\n"
"  fragment_color = vec4(clamp(c, 0.0, 1.0), 1.0);\n"
"}\n";

